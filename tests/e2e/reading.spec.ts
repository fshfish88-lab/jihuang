test('catalog pagination, filters, reload and back restore', async ({ page }) => {
  await page.goto('./wiki')
  await expect(page.locator('.wiki-catalog-item')).toHaveCount(24)
  await page.getByRole('button', { name: '料理', exact: true }).click()
  await expect(page.locator('.catalog-summary')).toContainText('50 条')
  await page.getByRole('link', { name: '下一页', exact: true }).click()
  await expect(page.locator('.catalog-summary')).toContainText('第 2 / 3 页')
  const title = await page.locator('.wiki-catalog-item h2').first().textContent()
  await page.locator('.wiki-catalog-item').nth(5).scrollIntoViewIfNeeded()
  const position = await page.evaluate(() => scrollY)
  await page.locator('.wiki-catalog-item').nth(5).click()
  await expect(page).toHaveURL(/wiki\//)
  await page.goBack()
  await expect(page.locator('.wiki-catalog-item h2').first()).toHaveText(title!)
  await expect(page.getByRole('button', { name: '料理', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await expect.poll(() => page.evaluate(() => scrollY)).toBeGreaterThan(Math.max(0, position - 180))
  await page.reload()
  await expect(page.locator('.catalog-summary')).toContainText('第 2 / 3 页')
  await page.getByLabel('料理用途').selectOption('health')
  await expect(page.locator('.catalog-summary')).toContainText('第 1 /')
  await expect(page.locator('.wiki-catalog-item')).not.toHaveCount(0)
})

