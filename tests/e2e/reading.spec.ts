import { test, expect } from '@playwright/test'

test('homepage question, exact aliases and search back state', async ({ page }) => {
  await page.goto('./search')
  const input = page.getByRole('searchbox')
  await input.fill('怎么复活')
  await expect(page.locator('.search-result')).not.toHaveCount(0)
  await expect(page).toHaveURL(/q=/)
  await page.locator('.search-result').filter({ has: page.getByRole('heading', { name: '告密的心' }) }).click()
  await expect(page).toHaveURL(/wiki\/tell-tale-heart/)
  await page.goBack()
  await expect(input).toHaveValue('怎么复活')
  await page.reload()
  await expect(input).toHaveValue('怎么复活')
  await input.fill('机器人')
  await expect(page.locator('.search-result h2').first()).toHaveText('WX-78')
})

