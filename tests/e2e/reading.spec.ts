test('search shortcut and mobile menu keyboard behavior', async ({ page }) => {
  await page.goto('./', { waitUntil: 'networkidle' })
  await page.keyboard.press('/')
  await expect(page.getByRole('searchbox')).toBeFocused()
  await page.getByRole('searchbox').fill('羊')
  await page.keyboard.press('/')
  await expect(page.getByRole('searchbox')).toHaveValue('羊/')
  await page.setViewportSize({ width: 375, height: 812 })
  await expect(page.getByRole('link', { name: '搜索攻略', exact: true })).toBeVisible()
  const menu = page.getByRole('button', { name: '切换导航' })
  await menu.click()
  await expect(page.locator('#mobile-menu')).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(page.locator('#mobile-menu')).toHaveCount(0)
  await expect(menu).toBeFocused()
})

