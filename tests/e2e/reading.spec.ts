test('Boss directory, canonical, sitemap and Chinese 404', async ({ page, request }) => {
  await page.goto('./bosses')
  await expect(page.locator('.content-card')).toHaveCount(15)
  await page.locator('.content-card').filter({ has: page.getByRole('heading', { name: '天体英雄' }) }).click()
  await expect(page).toHaveURL(/wiki\/celestial-champion/)
  await expect(page.locator('link[rel="canonical"]')).toHaveAttribute('href', 'https://fshfish88-lab.github.io/jihuang/wiki/celestial-champion/')
  await expect(page.locator('meta[property="og:image"]')).toHaveAttribute('content', /^https:\/\//)
  const sitemap = await request.get('./sitemap.xml')
  expect(sitemap.status()).toBe(200)
  expect(await sitemap.text()).toContain('/wiki/keystone/')
  const missing = await page.goto('./not-a-real-page')
  expect(missing?.status()).toBe(404)
  await expect(page.getByRole('heading', { name: '这页手记，似乎迷路了。' })).toBeVisible()
  await page.getByRole('link', { name: '回到首页' }).click()
  await expect(page.locator('.hero')).toBeVisible()
})
